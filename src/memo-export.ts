import {
  Document,
  Packer,
  Paragraph,
  TextRun,
  HeadingLevel,
  Footer,
  PageNumber,
  AlignmentType,
  Table,
  TableRow,
  TableCell,
  WidthType,
} from "docx";
import PDFDocument from "pdfkit";
import { existsSync } from "node:fs";
import { MemoService, memoSections } from "./memos.ts";
import { audit, transaction } from "./db.ts";
import { DomainError } from "./policy.ts";
const headings = [
  "Purpose",
  "Executive summary",
  "Details",
  "Analysis",
  "Recommendation",
  "Owner action",
  "Supporting data",
];
type Row = Record<string, any>;
export async function exportMemo(service: MemoService, input: Row) {
  const memo = service.get(input.id);
  if (!["docx", "pdf"].includes(input.format))
    throw new DomainError("Choose docx or pdf");
  const subject =
    String(memo.subject)
      .replace(/[^a-zA-Z0-9]+/g, "-")
      .slice(0, 60) || "Memo";
  const filename = `${memo.id}_${String(memo.created_at).slice(0, 10)}_${subject}.${input.format}`;
  const metadata = [
    ["Memo ID", memo.id],
    ["Date", memo.created_at],
    ["From", `${memo.author_name}, ${memo.author_role}`],
    ["Department", memo.department_id],
    ["To", "Human Owner"],
    ["Subject", memo.subject],
    ["Classification", memo.priority],
    ["Record status", memo.status],
    ["Execution authority", "None granted by this document"],
  ];
  const evidenceRow = service.db
    .prepare(
      "SELECT evidence FROM executive_report_closes WHERE company_id=? AND memo_id=?",
    )
    .get(service.p.company_id, memo.id);
  const evidence = evidenceRow
    ? JSON.parse(String(evidenceRow.evidence))
    : null;
  const table: string[][] = evidence
    ? [
        ["Agent", "Assigned", "Completed", "Cost USD", "Tokens"],
        ...evidence.agents.map((a: Row) => [
          a.name,
          String(a.assigned),
          String(a.completed),
          (a.spentMicros / 1e6).toFixed(6),
          a.tokens === null ? "Unavailable" : String(a.tokens),
        ]),
      ]
    : [];
  const sections = memoSections.map((key, i) => ({
    title: `${i + 1}. ${headings[i]}`,
    text: String(memo.body[key]),
  }));
  sections.push({
    title: "8. Record information",
    text: `Generated by ${memo.created_by}\nGenerated ${memo.created_at}\nRelated records: ${memo.related.map((m: Row) => m.id).join(", ") || "None"}\nReview history:\n${memo.history.map((h: Row) => `${h.created_at} — ${h.status}: ${h.reason}`).join("\n")}\nOwner review is distinct from a bound authorization to execute a financial or external action.`,
  });
  let bytes: Buffer;
  if (input.format === "docx") {
    const content: (Paragraph | Table)[] = [
      new Paragraph({ text: "BROKEN ARROW AI", heading: HeadingLevel.TITLE }),
      new Paragraph({ text: "MEMORANDUM", heading: HeadingLevel.HEADING_1 }),
      ...metadata.map(
        ([k, v]) =>
          new Paragraph({
            children: [
              new TextRun({ text: k + ": ", bold: true }),
              new TextRun(String(v)),
            ],
            spacing: { after: 80 },
          }),
      ),
    ];
    for (const section of sections) {
      content.push(
        new Paragraph({
          text: section.title,
          heading: HeadingLevel.HEADING_2,
          keepNext: true,
        }),
      );
      for (const line of section.text.split("\n"))
        content.push(new Paragraph({ text: line, spacing: { after: 100 } }));
      if (section.title.startsWith("7.") && table.length)
        content.push(
          new Table({
            width: { size: 100, type: WidthType.PERCENTAGE },
            rows: table.map(
              (cells, index) =>
                new TableRow({
                  tableHeader: index === 0,
                  cantSplit: true,
                  children: cells.map(
                    (text) =>
                      new TableCell({
                        margins: {
                          top: 100,
                          bottom: 100,
                          left: 100,
                          right: 100,
                        },
                        shading: index === 0 ? { fill: "E8EDF0" } : undefined,
                        children: [
                          new Paragraph({
                            children: [
                              new TextRun({
                                text,
                                bold: index === 0,
                                size: 20,
                              }),
                            ],
                          }),
                        ],
                      }),
                  ),
                }),
            ),
          }),
        );
    }
    bytes = await Packer.toBuffer(
      new Document({
        creator: "Broken Arrow AI",
        title: memo.subject,
        description: memo.id,
        styles: {
          default: {
            document: {
              run: { font: "Arial", size: 22, color: "000000" },
              paragraph: { spacing: { line: 276 } },
            },
            title: { run: { font: "Arial", size: 36, color: "000000" } },
            heading1: { run: { font: "Arial", size: 28, color: "000000" } },
            heading2: { run: { font: "Arial", size: 24, color: "000000" } },
          },
        },
        sections: [
          {
            properties: {
              page: {
                margin: { top: 1080, bottom: 1080, left: 1080, right: 1080 },
              },
            },
            footers: {
              default: new Footer({
                children: [
                  new Paragraph({
                    alignment: AlignmentType.RIGHT,
                    children: [
                      new TextRun({ text: memo.id + " · Page ", size: 16 }),
                      new TextRun({ children: [PageNumber.CURRENT], size: 16 }),
                    ],
                  }),
                ],
              }),
            },
            children: content,
          },
        ],
      }),
    );
  } else {
    const font = [
      process.env.MEMO_PDF_FONT,
      "C:/Windows/Fonts/arial.ttf",
      "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    ].find((p) => p && existsSync(p));
    if (!font)
      throw new DomainError(
        "Configure MEMO_PDF_FONT to an installed Unicode TrueType font",
        503,
      );
    bytes = await new Promise<Buffer>((resolve, reject) => {
      const doc = new PDFDocument({
          size: "A4",
          margin: 54,
          bufferPages: true,
          info: {
            Title: memo.subject,
            Author: "Broken Arrow AI",
            Subject: memo.id,
          },
        }),
        chunks: Buffer[] = [];
      doc.on("data", (b) => chunks.push(b));
      doc.on("error", reject);
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc
        .font(font)
        .fontSize(18)
        .text("BROKEN ARROW AI")
        .moveDown(0.3)
        .fontSize(14)
        .text("MEMORANDUM")
        .moveDown(0.5);
      doc.fontSize(10);
      for (const [k, v] of metadata) doc.text(k + ": " + v);
      doc.moveDown();
      for (const section of sections) {
        if (doc.y > 710) doc.addPage();
        doc.fontSize(12).text(section.title).moveDown(0.3);
        doc.fontSize(10).text(section.text, { lineGap: 3 }).moveDown(0.7);
        if (section.title.startsWith("7.") && table.length) {
          const widths = [167, 65, 70, 85, 100],
            start = 54;
          for (const cells of table) {
            const h =
              Math.max(
                ...cells.map((t, i) =>
                  doc.heightOfString(t, { width: widths[i] - 10 }),
                ),
              ) + 12;
            if (doc.y + h > 760) doc.addPage();
            const y = doc.y;
            let x = start;
            cells.forEach((t, i) => {
              doc
                .save()
                .strokeColor("#D9D9D9")
                .rect(x, y, widths[i], h)
                .stroke()
                .restore();
              doc.text(t, x + 5, y + 6, { width: widths[i] - 10 });
              x += widths[i];
            });
            doc.x = 54;
            doc.y = y + h;
          }
          doc.moveDown();
        }
      }
      const pages = doc.bufferedPageRange();
      for (let i = 0; i < pages.count; i++) {
        doc.switchToPage(i);
        const bottomMargin = doc.page.margins.bottom;
        doc.page.margins.bottom = 0;
        doc
          .fontSize(8)
          .text(`${memo.id} · Page ${i + 1} of ${pages.count}`, 54, 792, {
            width: 487,
            align: "right",
            lineBreak: false,
          });
        doc.page.margins.bottom = bottomMargin;
      }
      doc.end();
    });
  }
  transaction(service.db, () => {
    service.authenticate();
    audit(
      service.db,
      service.p.company_id,
      service.p.id,
      "memo.exported",
      memo.id,
      "SUCCESS",
      { format: input.format, bytes: bytes.length },
    );
  });
  return {
    filename,
    bytes,
    mime:
      input.format === "pdf"
        ? "application/pdf"
        : "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
  };
}
